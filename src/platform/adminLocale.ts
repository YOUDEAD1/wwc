const positions: Record<Lang, number> = { en: 0, ar: 1, vi: 2, zh: 3 };
export function adminLabel(value: string, lang: Lang) {
  const row = rows.find((r) => r.includes(value));
  if (row) return row[positions[lang]]!;
  for (const source of ['ar', 'en'] as const) {
    const key = Object.keys(LOCALES[source]).find((k) => LOCALES[source][k] === value);
    if (key && LOCALES[lang][key]) return LOCALES[lang][key]!;
  }
  return value;
}
export function adminBody(value: string, lang: Lang) {
  if (lang === 'ar') return value;
  let text = value;
  for (const row of [...rows].sort((a, b) => b[1]!.length - a[1]!.length))
    if (row[1] && text.includes(row[1])) text = text.split(row[1]).join(row[positions[lang]]!);
  return text;
}
